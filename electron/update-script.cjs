// Zenith — in-app update PowerShell script builder (pure Node, no Electron).
//
// Why this exists (v1.0.5): the v1.0.3 updater spawned an INLINE PowerShell
// `-Command` string that (a) slept a FIXED 2 seconds before running the
// installer — Electron often takes longer than that to fully quit, so the
// still-running Zenith.exe stayed file-locked and the NSIS installer, in
// silent /S mode, silently skipped overwriting it and exited 0; and
// (b) checked NOTHING — no installer exit code, no verification that the
// new version actually landed, no log, no error shown. The user pressed
// Update twice on v1.0.3: download ran, app closed, nothing relaunched,
// still v1.0.3. This builder produces a .ps1 FILE (no inline -Command
// quoting fragility) that:
//   1. waits for the Zenith process to FULLY exit (poll, up to 60s),
//   2. runs the installer silently and captures its exit code,
//   3. VERIFIES the install (registry Version + Zenith.exe file version),
//   4. relaunches the new version and confirms the process started,
//   5. logs every step to a file, and shows a real error dialog on
//      failure instead of failing silently.
//
// Pure Node so it can be unit-tested on any machine (no Electron needed).
// PowerShell text contains `$(...)` subexpressions but no `${...}` — the
// only `${...}` in this file are the JS interpolations below.

function psQuote(value) {
  // PowerShell single-quoted literal; a ' inside is doubled.
  return "'" + String(value).replace(/'/g, "''") + "'";
}

function buildUpdateScript({ installerPath, version, installDirHint, logPath }) {
  const installer = psQuote(installerPath);
  const targetVersion = psQuote(version);
  const hint = psQuote(installDirHint);
  const log = psQuote(logPath);
  return [
    '# Zenith in-app update script (generated by the app).',
    '# Waits for Zenith to fully exit, installs silently, VERIFIES the new',
    '# version, then relaunches. Every step is logged; failures show a',
    '# dialog instead of failing silently.',
    '',
    `$logPath = ${log}`,
    `$installerPath = ${installer}`,
    `$targetVersion = ${targetVersion}`,
    `$installDirHint = ${hint}`,
    '',
    'function Write-UpdateLog($msg) {',
    '  $line = "$(Get-Date -Format \'yyyy-MM-dd HH:mm:ss\') $msg"',
    '  Add-Content -Path $logPath -Value $line -ErrorAction SilentlyContinue',
    '}',
    '',
    'function Show-UpdateError($msg) {',
    '  Write-UpdateLog("ERROR: $msg")',
    '  try {',
    '    Add-Type -AssemblyName System.Windows.Forms -ErrorAction Stop',
    "    [System.Windows.Forms.MessageBox]::Show($msg, 'Zenith update', 'OK', 'Error') | Out-Null",
    '  } catch { }',
    '}',
    '',
    'Write-UpdateLog("Update script started for Zenith $targetVersion")',
    'Write-UpdateLog("Installer: $installerPath")',
    '',
    '# 1. Wait for the Zenith process to FULLY exit (up to 60s).',
    '#    A fixed 2s sleep was not enough: while Zenith.exe is still',
    '#    running its file is locked, and the NSIS installer in silent',
    '#    mode silently skips locked files and exits 0.',
    '$deadline = (Get-Date).AddSeconds(30)',
    "while ((Get-Process -Name 'Zenith' -ErrorAction SilentlyContinue) -and (Get-Date) -lt $deadline) {",
    '  Start-Sleep -Milliseconds 500',
    '}',
    "if (Get-Process -Name 'Zenith' -ErrorAction SilentlyContinue) {",
    "  Stop-Process -Name 'Zenith' -Force -ErrorAction SilentlyContinue",
    '  Start-Sleep -Seconds 1',
    '}',
    "Write-UpdateLog('Zenith process exited')",
    '',
    '# 2. Run the installer silently and capture its exit code.',
    'if (-not (Test-Path $installerPath)) {',
    '  Show-UpdateError("Downloaded installer not found. Please try the update again. (Log: $logPath)")',
    '  exit 1',
    '}',
    'try { Unblock-File -Path $installerPath -ErrorAction SilentlyContinue } catch { }',
    "Write-UpdateLog('Running installer silently...')",
    "$proc = Start-Process -FilePath $installerPath -ArgumentList '/S' -Wait -PassThru",
    'Write-UpdateLog("Installer exit code: $($proc.ExitCode)")',
    'if ($proc.ExitCode -ne 0) {',
    '  Show-UpdateError("The installer failed (exit code $($proc.ExitCode)). The update did not install. Please try again or install the new version manually from GitHub. (Log: $logPath)")',
    '  exit 1',
    '}',
    '',
    '# 3. Verify the install actually happened.',
    "$regDir = (Get-ItemProperty -Path 'HKCU:\\Software\\Zenith' -Name InstallDir -ErrorAction SilentlyContinue).InstallDir",
    "$regVersion = (Get-ItemProperty -Path 'HKCU:\\Software\\Zenith' -Name Version -ErrorAction SilentlyContinue).Version",
    '$installDir = if ($regDir) { $regDir } else { $installDirHint }',
    'Write-UpdateLog("Install dir: $installDir; registry version: $regVersion")',
    "$targetExe = Join-Path $installDir 'Zenith.exe'",
    'if (-not (Test-Path $targetExe)) {',
    '  Show-UpdateError("Update finished but Zenith.exe was not found at $installDir. Please install the new version manually from GitHub. (Log: $logPath)")',
    '  exit 1',
    '}',
    '$fileVersion = ([System.Diagnostics.FileVersionInfo]::GetVersionInfo($targetExe)).FileVersion',
    'Write-UpdateLog("Zenith.exe file version: $fileVersion")',
    'if ($regVersion -ne $targetVersion -or $fileVersion -notlike "$targetVersion*") {',
    '  Show-UpdateError("The installer finished but Zenith is still on version $regVersion instead of $targetVersion. Please install the new version manually from GitHub. (Log: $logPath)")',
    '  exit 1',
    '}',
    '',
    '# 4. Relaunch the new version and confirm the process started.',
    "Write-UpdateLog('Launching new Zenith...')",
    'Start-Process -FilePath $targetExe',
    'Start-Sleep -Seconds 3',
    "if (Get-Process -Name 'Zenith' -ErrorAction SilentlyContinue) {",
    "  Write-UpdateLog('Relaunch OK - new Zenith is running')",
    '} else {',
    "  Write-UpdateLog('WARNING: Zenith did not appear after relaunch - please open it manually')",
    '}',
    '',
    '# 5. Clean up the downloaded installer (only on success).',
    'Remove-Item -Path $installerPath -Force -ErrorAction SilentlyContinue',
    'Write-UpdateLog("Update to $targetVersion finished OK")',
    '',
  ].join('\r\n');
}

module.exports = { buildUpdateScript, psQuote };
